using System.Collections.Immutable;
using System.Reflection;
using System.Runtime.Loader;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;

namespace Validly.SourceGeneration.Tests;

/// <summary>
/// Third-party generator built on the API: generates "{Entity}Dto" partial classes with the entity's properties
/// and copies the entity's validation to them. Validly's own generator does not run in these tests.
/// </summary>
internal sealed class SampleDtoGenerator(ValidlyGenerationOptions? options = null) : IIncrementalGenerator
{
	public void Initialize(IncrementalGeneratorInitializationContext context)
	{
		var validators = ValidlySourceGeneration.GetValidators(context);
		var entities = context.SyntaxProvider.ForAttributeWithMetadataName(
			"Sample.GenerateDtoAttribute",
			static (_, _) => true,
			static (ctx, _) => ctx.TargetSymbol.ToDisplayString()
		);

		// Entities from referenced assemblies, listed by an assembly attribute
		var referencedEntities = context.CompilationProvider.SelectMany(
			static (compilation, _) =>
				compilation
					.Assembly.GetAttributes()
					.Where(a => a.AttributeClass?.Name == "GenerateDtoForAttribute")
					.Select(a => ((INamedTypeSymbol)a.ConstructorArguments[0].Value!).ToDisplayString())
		);

		context.RegisterSourceOutput(
			entities.Collect().Combine(referencedEntities.Collect()).Combine(validators).Combine(context.CompilationProvider),
			(spc, input) =>
			{
				var (((sourceEntities, metadataEntities), catalog), compilation) = input;

				foreach (string entityName in sourceEntities.Concat(metadataEntities))
				{
					var entity = compilation.GetTypeByMetadataName(entityName)!;
					var effectiveOptions = (options ?? new ValidlyGenerationOptions()) with
					{
						TypeName = entity.Name + "Dto",
						Namespace = "Sample.Dtos",
					};

					// The DTO itself
					var dto = new StringBuilder();
					dto.AppendLine("namespace Sample.Dtos;").AppendLine($"public partial class {entity.Name}Dto").AppendLine("{");

					for (var type = entity; type is { SpecialType: not SpecialType.System_Object }; type = type.BaseType)
					{
						foreach (var property in type.GetMembers().OfType<IPropertySymbol>())
						{
							string? name = effectiveOptions.PropertyMap is null ? property.Name : effectiveOptions.PropertyMap(property.Name);

							if (name is not null)
							{
								dto.AppendLine($"    public {property.Type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat.AddMiscellaneousOptions(SymbolDisplayMiscellaneousOptions.IncludeNullableReferenceTypeModifier))} {name} {{ get; set; }}");
							}
						}
					}

					dto.AppendLine("}");
					spc.AddSource($"{entity.Name}Dto.g.cs", dto.ToString());

					// Its validation, generated by Validly
					var validation = ValidlySourceGeneration.Generate(entity, compilation, effectiveOptions, catalog);
					spc.AddSource(validation.HintName, validation.SourceText);
				}
			}
		);
	}
}

public class DtoGeneratorTests
{
	private const string Attributes = """
		namespace Sample
		{
			[System.AttributeUsage(System.AttributeTargets.Class)]
			public sealed class GenerateDtoAttribute : System.Attribute;

			[System.AttributeUsage(System.AttributeTargets.Assembly, AllowMultiple = true)]
			public sealed class GenerateDtoForAttribute(System.Type type) : System.Attribute;
		}
		""";

	private static readonly string FullSource = EntitySource + Environment.NewLine + Attributes;

	private const string EntitySource = """
		#nullable enable
		using Validly.Validators;

		namespace Sample.Entities
		{
			public abstract class EntityBase
			{
				[Required]
				public string? Id { get; set; }
			}

			// No [Validatable]; the entity only carries the rules
			[Sample.GenerateDto]
			public class User : EntityBase
			{
				[Required]
				[LengthBetween(3, 20)]
				public string? UserName { get; set; }

				[Between(18, 120)]
				public int Age { get; set; }

				[EmailAddress]
				public string? Email { get; set; }
			}
		}
		""";

	[Fact]
	public void Dto_GetsTheValidationOfTheEntity()
	{
		var assembly = CompileWithGenerator(new SampleDtoGenerator(), FullSource);
		dynamic dto = Create(assembly, "Sample.Dtos.UserDto");
		dto.Id = "1";
		dto.UserName = "ab";
		dto.Age = 10;
		dto.Email = "not-an-email";

		using ValidationResult result = dto.Validate();

		Assert.Equal(
			["UserName", "Age", "Email"],
			result.Properties.Where(p => !p.IsSuccess).Select(p => p.PropertyPath)
		);
	}

	[Fact]
	public void Dto_BasePropertiesAreIncluded_ValidDtoIsValid()
	{
		var assembly = CompileWithGenerator(new SampleDtoGenerator(), FullSource);
		dynamic dto = Create(assembly, "Sample.Dtos.UserDto");
		dto.UserName = "tony";
		dto.Age = 30;
		dto.Email = "tony@stark.com";

		using (ValidationResult missingId = dto.Validate())
		{
			Assert.Equal("Id", Assert.Single(missingId.Properties, p => !p.IsSuccess).PropertyPath);
		}

		dto.Id = "1";

		using ValidationResult valid = dto.Validate();
		Assert.True(valid.IsSuccess);
	}

	[Fact]
	public void PropertyMap_ExcludesAndRenamesProperties()
	{
		var options = new ValidlyGenerationOptions
		{
			PropertyMap = name => name switch
			{
				"Id" => null,
				"UserName" => "Login",
				_ => name,
			},
		};

		var assembly = CompileWithGenerator(new SampleDtoGenerator(options), FullSource);
		dynamic dto = Create(assembly, "Sample.Dtos.UserDto");
		dto.Login = "ab";
		dto.Age = 30;
		dto.Email = "tony@stark.com";

		using ValidationResult result = dto.Validate();

		Assert.Equal("Login", Assert.Single(result.Properties, p => !p.IsSuccess).PropertyPath);
		Assert.DoesNotContain(result.Properties, p => p.PropertyPath == "Id");
	}

	[Fact]
	public void EntityFromReferencedAssembly_IsSupported()
	{
		// Entities compiled into another assembly (metadata symbols)
		var entitiesImage = Emit(CreateCompilation("Entities", FullSource, []));
		var entitiesReference = MetadataReference.CreateFromImage(entitiesImage);

		const string consumerSource = """
			[assembly: Sample.GenerateDtoFor(typeof(Sample.Entities.User))]
			""";

		var loadContext = new TestLoadContext(("Entities", entitiesImage));
		var assembly = CompileWithGenerator(new SampleDtoGenerator(), consumerSource, [entitiesReference], loadContext);

		dynamic dto = Create(assembly, "Sample.Dtos.UserDto");
		dto.Id = "1";
		dto.UserName = "tony";
		dto.Age = 5;
		dto.Email = "tony@stark.com";

		using ValidationResult result = dto.Validate();

		Assert.Equal("Age", Assert.Single(result.Properties, p => !p.IsSuccess).PropertyPath);
	}

	[Fact]
	public void GeneratedSource_IsSelfContained()
	{
		var compilation = CreateCompilation("Gen", FullSource, []);
		var user = compilation.GetTypeByMetadataName("Sample.Entities.User")!;

		var result = ValidlySourceGeneration.Generate(user, compilation, new ValidlyGenerationOptions { TypeName = "UserDto" });

		Assert.Equal("Sample.Entities.UserDto.Validator.g.cs", result.HintName);
		Assert.DoesNotContain("using ", result.SourceText.Split('\n').Where(l => l.StartsWith("using ")));
		Assert.Contains("partial class UserDto", result.SourceText);
	}

	[Fact]
	public void ValidatorCatalog_IsEquatable()
	{
		var compilation = CreateCompilation("Gen", FullSource, []);

		var first = ValidlySourceGeneration.GetValidators(compilation);
		var second = ValidlySourceGeneration.GetValidators(compilation.AddSyntaxTrees(CSharpSyntaxTree.ParseText("class Unrelated {}")));

		Assert.True(first.Count > 10);
		Assert.Equal(first, second);
	}

	private static dynamic Create(Assembly assembly, string typeName) =>
		Activator.CreateInstance(assembly.GetType(typeName, throwOnError: true)!)!;

	private static Assembly CompileWithGenerator(
		IIncrementalGenerator generator,
		string source,
		MetadataReference[]? references = null,
		TestLoadContext? loadContext = null
	)
	{
		var compilation = CreateCompilation("Consumer", source, references ?? []);

		CSharpGeneratorDriver
			.Create([generator.AsSourceGenerator()], parseOptions: new CSharpParseOptions(LanguageVersion.Latest))
			.RunGeneratorsAndUpdateCompilation(compilation, out var output, out var diagnostics);

		Assert.Empty(diagnostics.Where(d => d.Severity == DiagnosticSeverity.Error));

		return (loadContext ?? new TestLoadContext()).LoadFromStream(new MemoryStream(Emit(output)));
	}

	private static CSharpCompilation CreateCompilation(string name, string source, MetadataReference[] references)
	{
		var trusted = ((string)AppContext.GetData("TRUSTED_PLATFORM_ASSEMBLIES")!).Split(Path.PathSeparator);

		return CSharpCompilation.Create(
			name,
			[CSharpSyntaxTree.ParseText(source, new CSharpParseOptions(LanguageVersion.Latest))],
			trusted
				.Select(path => (MetadataReference)MetadataReference.CreateFromFile(path))
				.Append(MetadataReference.CreateFromFile(typeof(ValidatableAttribute).Assembly.Location))
				.Concat(references)
				.ToImmutableArray(),
			new CSharpCompilationOptions(OutputKind.DynamicallyLinkedLibrary, nullableContextOptions: NullableContextOptions.Enable)
		);
	}

	private static byte[] Emit(Compilation compilation)
	{
		using var stream = new MemoryStream();
		var result = compilation.Emit(stream);

		Assert.True(
			result.Success,
			string.Join(Environment.NewLine, result.Diagnostics.Where(d => d.Severity == DiagnosticSeverity.Error))
		);

		return stream.ToArray();
	}

	private sealed class TestLoadContext(params (string Name, byte[] Image)[] dependencies) : AssemblyLoadContext(isCollectible: true)
	{
		protected override Assembly? Load(AssemblyName assemblyName)
		{
			foreach (var (name, image) in dependencies)
			{
				if (assemblyName.Name == name)
				{
					return LoadFromStream(new MemoryStream(image));
				}
			}

			return null;
		}
	}
}

public class ApiAssemblyTests
{
	[Fact]
	public void ApiAssembly_DoesNotContainAGenerator()
	{
		// Shipped next to third-party generators; Validly's generator must not run from it
		var generatorTypes = typeof(ValidlySourceGeneration)
			.Assembly.GetTypes()
			.Where(t =>
				t.GetCustomAttributes(typeof(GeneratorAttribute), inherit: false).Length != 0
				|| t.GetCustomAttributes(typeof(Microsoft.CodeAnalysis.Diagnostics.DiagnosticAnalyzerAttribute), inherit: false).Length != 0
			);

		Assert.Empty(generatorTypes);
	}
}
