using System.Collections.Immutable;
using System.Reflection;
using System.Runtime.Loader;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;

namespace Validly.SourceGenerator.Tests;

/// <summary>
/// Validatable objects inheriting from validatable objects declared in another (already compiled) assembly
/// </summary>
public class CrossAssemblyInheritanceTests
{
	private const string ImplicitUsings = """
		global using System;
		global using System.Collections.Generic;
		global using System.Linq;
		global using System.Threading;
		global using System.Threading.Tasks;

		""";

	private const string DerivedSource = """
		using Validly;
		using Validly.Extensions.Validators.Strings;

		namespace Derived;

		[Validatable]
		public partial class Dog : Base.Animal
		{
			[MinLength(3)]
			public string? Breed { get; set; }
		}
		""";

	[Fact]
	public void BaseGeneratedByThisVersion_DerivedCallsItsCoreMethod()
	{
		const string baseSource = """
			using Validly;
			using Validly.Extensions.Validators.Common;

			namespace Base;

			[Validatable]
			public partial class Animal
			{
				[Required]
				public string? Name { get; set; }
			}
			""";

		byte[] baseImage = Compile("Base", baseSource, runGenerator: true, out var baseReference);
		var derivedRun = CompileWithGenerator("Derived", DerivedSource, [baseReference], out byte[] derivedImage);

		string generated = derivedRun.GeneratedSources.Single().SourceText.ToString();
		Assert.Contains("base.ValidlyValidateCoreAsync(context, serviceProvider, ct)", generated);
		// Sync base (detected from metadata) keeps the derived validation sync
		Assert.Contains("public override global::Validly.ValidationResult Validate()", generated);

		AssertDerivedValidation(baseImage, derivedImage);
	}

	[Fact]
	public void AsyncBaseFromMetadata_DerivedIsAsync()
	{
		const string baseSource = """
			using Validly;
			using Validly.Extensions.Validators.Common;

			namespace Base;

			[Validatable]
			public partial class Animal
			{
				[Required]
				public string? Name { get; set; }

				private async Task<ValidationMessage?> AfterValidate()
				{
					await Task.Yield();
					return null;
				}
			}
			""";

		byte[] baseImage = Compile("Base", baseSource, runGenerator: true, out var baseReference);
		var derivedRun = CompileWithGenerator("Derived", DerivedSource, [baseReference], out byte[] derivedImage);

		string generated = derivedRun.GeneratedSources.Single().SourceText.ToString();
		Assert.Contains("await baseTask", generated);
		Assert.DoesNotContain("Validate()", generated.Replace("ValidateAsync(", string.Empty));

		AssertDerivedValidation(baseImage, derivedImage, isAsync: true);
	}

	[Fact]
	public void BaseGeneratedByValidly13_DerivedFallsBackToItsValidateAsync()
	{
		// Shape of the code generated by Validly 1.3
		const string legacyBaseSource = """
			using Validly;
			using Validly.Extensions.Validators.Common;

			namespace Base;

			[Validatable]
			public partial class Animal : global::Validly.IValidatable, global::Validly.Validators.IInternalValidationInvoker
			{
				private static readonly RequiredAttribute NameRule = new();

				[Required]
				public string? Name { get; set; }

				private global::System.WeakReference<global::Validly.ValidationContext>? _validationContext;

				void global::Validly.Validators.IInternalValidationInvoker.SetValidationContext(global::Validly.ValidationContext validationContext)
				{
					this._validationContext = new global::System.WeakReference<global::Validly.ValidationContext>(validationContext, false);
				}

				global::Validly.ValidationContext? global::Validly.Validators.IInternalValidationInvoker.GetValidationContext()
				{
					if (this._validationContext == null)
					{
						return null;
					}

					return this._validationContext.TryGetTarget(out var existingContext) ? existingContext : throw new InvalidOperationException();
				}

				async ValueTask<global::Validly.ValidationResult> global::Validly.IValidatable.ValidateAsync(global::System.IServiceProvider _, CancellationToken ct)
				{
					return await ValidateAsync(ct);
				}

				public virtual global::Validly.ValidationResult Validate()
				{
					var task = ValidateAsync(default);
					return task.Result;
				}

				public virtual ValueTask<global::Validly.ValidationResult> ValidateAsync(CancellationToken ct = default)
				{
					global::Validly.IInternalValidationResult? result = null;
					var contextSet = ((global::Validly.Validators.IInternalValidationInvoker)this).GetValidationContext();
					var context = contextSet == null ? global::Validly.ValidationContext.Create(this) : contextSet;
					using var _ = new global::Validly.ValidationContextDisposer(context, contextSet == null);

					result = (global::Validly.IInternalValidationResult)global::Validly.ExtendableValidationResult.Create(1);
					context.SetProperty("Name");
					var propertyResult = result.InitProperty("Name");
					propertyResult.Add(NameRule.IsValid(Name));

					return new ValueTask<global::Validly.ValidationResult>((global::Validly.ValidationResult)result);
				}
			}
			""";

		byte[] baseImage = Compile("Base", legacyBaseSource, runGenerator: false, out var baseReference);
		var derivedRun = CompileWithGenerator("Derived", DerivedSource, [baseReference], out byte[] derivedImage);

		string generated = derivedRun.GeneratedSources.Single().SourceText.ToString();
		Assert.Contains("base.ValidateAsync(ct)", generated);
		Assert.DoesNotContain("base.ValidlyValidateCoreAsync", generated);

		AssertDerivedValidation(baseImage, derivedImage);
	}

	private static void AssertDerivedValidation(byte[] baseImage, byte[] derivedImage, bool isAsync = false)
	{
		var loadContext = new TestLoadContext(baseImage);
		Assembly derivedAssembly = loadContext.LoadFromStream(new MemoryStream(derivedImage));
		Type dogType = derivedAssembly.GetType("Derived.Dog")!;

		dynamic dog = Activator.CreateInstance(dogType)!;
		dog.Name = null;
		dog.Breed = "ab";

		ValidationResult result = isAsync
			? ((ValueTask<ValidationResult>)dog.ValidateAsync(default(CancellationToken))).AsTask().GetAwaiter().GetResult()
			: (ValidationResult)dog.Validate();

		using (result)
		{
			Assert.Equal(["Name", "Breed"], result.Properties.Select(p => p.PropertyPath));
			Assert.All(result.Properties, p => Assert.False(p.IsSuccess));
		}

		dog.Name = "Rex";
		dog.Breed = "Husky";

		ValidationResult validResult = isAsync
			? ((ValueTask<ValidationResult>)dog.ValidateAsync(default(CancellationToken))).AsTask().GetAwaiter().GetResult()
			: (ValidationResult)dog.Validate();

		using (validResult)
		{
			Assert.True(validResult.IsSuccess);
		}
	}

	private static GeneratorRunResult CompileWithGenerator(
		string assemblyName,
		string source,
		MetadataReference[] references,
		out byte[] image
	)
	{
		var compilation = CreateCompilation(assemblyName, source, references);

		var driver = CSharpGeneratorDriver
			.Create(
				[new ValidatableSourceGenerator().AsSourceGenerator()],
				parseOptions: new CSharpParseOptions(LanguageVersion.Latest)
			)
			.RunGeneratorsAndUpdateCompilation(compilation, out var outputCompilation, out _);

		image = Emit(outputCompilation);
		return driver.GetRunResult().Results.Single();
	}

	private static byte[] Compile(string assemblyName, string source, bool runGenerator, out MetadataReference reference)
	{
		byte[] image;

		if (runGenerator)
		{
			CompileWithGenerator(assemblyName, source, [], out image);
		}
		else
		{
			image = Emit(CreateCompilation(assemblyName, source, []));
		}

		reference = MetadataReference.CreateFromImage(image);
		return image;
	}

	private static CSharpCompilation CreateCompilation(string assemblyName, string source, MetadataReference[] references)
	{
		var trustedAssemblies = ((string)AppContext.GetData("TRUSTED_PLATFORM_ASSEMBLIES")!).Split(Path.PathSeparator);

		return CSharpCompilation.Create(
			assemblyName,
			[CSharpSyntaxTree.ParseText(ImplicitUsings + source, new CSharpParseOptions(LanguageVersion.Latest))],
			trustedAssemblies
				.Select(path => (MetadataReference)MetadataReference.CreateFromFile(path))
				.Append(MetadataReference.CreateFromFile(typeof(ValidatableAttribute).Assembly.Location))
				.Append(
					MetadataReference.CreateFromFile(
						typeof(Validly.Extensions.Validators.Strings.MinLengthAttribute).Assembly.Location
					)
				)
				.Concat(references)
				.ToImmutableArray(),
			new CSharpCompilationOptions(OutputKind.DynamicallyLinkedLibrary, nullableContextOptions: NullableContextOptions.Enable)
		);
	}

	private static byte[] Emit(Compilation compilation)
	{
		using var stream = new MemoryStream();
		var emitResult = compilation.Emit(stream);

		Assert.True(
			emitResult.Success,
			string.Join(
				Environment.NewLine,
				emitResult.Diagnostics.Where(d => d.Severity == DiagnosticSeverity.Error).Select(d => d.ToString())
			)
		);

		return stream.ToArray();
	}

	/// <summary>
	/// Loads the compiled base assembly; Validly assemblies are shared with the test (default context)
	/// </summary>
	private sealed class TestLoadContext(byte[] baseImage) : AssemblyLoadContext(isCollectible: true)
	{
		private Assembly? _baseAssembly;

		protected override Assembly? Load(AssemblyName assemblyName)
		{
			if (assemblyName.Name == "Base")
			{
				return _baseAssembly ??= LoadFromStream(new MemoryStream(baseImage));
			}

			return null;
		}
	}
}
