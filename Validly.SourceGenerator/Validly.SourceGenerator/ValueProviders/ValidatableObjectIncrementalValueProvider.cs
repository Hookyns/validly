using System.Collections.Immutable;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Validly.SourceGenerator.Dtos;
using Validly.SourceGenerator.Utils;
using Validly.SourceGenerator.Utils.Mapping;

namespace Validly.SourceGenerator.ValueProviders;

internal static class ValidatableObjectIncrementalValueProvider
{
	public static IncrementalValuesProvider<ObjectProperties> Get(IncrementalGeneratorInitializationContext initContext)
	{
		return initContext
			.SyntaxProvider.ForAttributeWithMetadataName(
				Consts.ValidatableAttributeQualifiedName,
				predicate: static (node, _) => node is ClassDeclarationSyntax or RecordDeclarationSyntax,
				transform: static (context, cancellationToken) => GetObjectProperties(context, cancellationToken)
			)
			.WhereNotNull();
	}

	private static ObjectProperties? GetObjectProperties(
		GeneratorAttributeSyntaxContext context,
		CancellationToken cancellationToken
	)
	{
		if (
			context.TargetSymbol is not INamedTypeSymbol typeSymbol
			|| context.TargetNode is not TypeDeclarationSyntax targetNode
		)
		{
			return null;
		}

		return MapObject(typeSymbol, targetNode, context.SemanticModel, cancellationToken);
	}

	private static ObjectProperties MapObject(
		INamedTypeSymbol typeSymbol,
		TypeDeclarationSyntax targetNode,
		SemanticModel semanticModel,
		CancellationToken cancellationToken
	)
	{
		var usings = GetUsings(targetNode);
		var membersSymbols = typeSymbol.GetMembers();
		var methods = GetMethods(membersSymbols, semanticModel);
		var properties = GetProperties(membersSymbols, semanticModel);

		var validatableAttribute = typeSymbol
			.GetAttributes()
			.First(attr => attr.AttributeClass?.GetQualifiedName() == Consts.ValidatableAttributeQualifiedName);

		return new ObjectProperties
		{
			UseAutoValidators = GetUseAutoValidatorsValue(validatableAttribute),
			ExitEarly = GetGetExitEarlyValue(validatableAttribute),
			Usings = new EquatableArray<string>(usings.Select(static usingSyntax => usingSyntax.ToString()).ToArray()),
			ClassOrRecordKeyword = typeSymbol.IsRecord ? "record" : "class",
			Accessibility = typeSymbol.DeclaredAccessibility,
			Name = typeSymbol.Name,
			TypeParameters = new EquatableArray<string>(
				typeSymbol
					.TypeParameters.Select(static typeParameter =>
						typeParameter.ToDisplayString(SymbolDisplayFormat.MinimallyQualifiedFormat)
					)
					.ToArray()
			),
			Namespace = typeSymbol.ContainingNamespace.CanBeReferencedByName
				? typeSymbol.ContainingNamespace.ToString()
				: null,
			Properties = new EquatableArray<PropertyProperties>(properties),
			Methods = new EquatableArray<MethodProperties>(methods),
			BaseObject = GetBaseObject(typeSymbol, semanticModel.Compilation, cancellationToken),
			IsSealed = typeSymbol.IsSealed,
			BeforeValidateMethod = methods.FirstOrDefault(static m => m.MethodName == Consts.BeforeValidateMethodName),
			AfterValidateMethod = methods.FirstOrDefault(static m => m.MethodName == Consts.AfterValidateMethodName),
		};
	}

	/// <summary>
	/// Find the nearest validatable ancestor; non-validatable types in between are skipped
	/// </summary>
	private static BaseObjectProperties? GetBaseObject(
		INamedTypeSymbol typeSymbol,
		Compilation compilation,
		CancellationToken cancellationToken
	)
	{
		for (var baseType = typeSymbol.BaseType; baseType is not null; baseType = baseType.BaseType)
		{
			cancellationToken.ThrowIfCancellationRequested();

			if (baseType.SpecialType == SpecialType.System_Object || !IsValidatable(baseType))
			{
				continue;
			}

			var definition = baseType.OriginalDefinition;

			// Declared in this compilation; generated by this generator, so its model is mapped the same way
			if (
				SymbolEqualityComparer.Default.Equals(definition.ContainingAssembly, compilation.Assembly)
				&& definition.DeclaringSyntaxReferences.FirstOrDefault()?.GetSyntax(cancellationToken)
					is TypeDeclarationSyntax baseNode
			)
			{
				return new BaseObjectProperties
				{
					IsFromSource = true,
					Object = MapObject(
						definition,
						baseNode,
						compilation.GetSemanticModel(baseNode.SyntaxTree),
						cancellationToken
					),
					HasCoreMethod = true,
					RequiresServiceProvider = false,
					IsAsync = false,
				};
			}

			// Referenced assembly; the shape is read from its (generated) members
			var coreMethod = FindMethod(baseType, Consts.ValidateCoreMethodName, static _ => true);
			var validateAsyncWithServiceProvider = FindMethod(
				baseType,
				Consts.ValidateAsyncMethodName,
				static method =>
					method.DeclaredAccessibility == Accessibility.Public
					&& method.Parameters.Length == 2
					&& method.Parameters[0].Type.ToDisplayString() == "System.IServiceProvider"
			);
			var validateAsync = FindMethod(
				baseType,
				Consts.ValidateAsyncMethodName,
				static method => method.DeclaredAccessibility == Accessibility.Public
			);

			// Async methods carry the AsyncStateMachine attribute in metadata
			var validationMethod = coreMethod ?? validateAsync;
			bool isAsync =
				validationMethod
					?.GetAttributes()
					.Any(static attr =>
						attr.AttributeClass?.GetQualifiedName() == Consts.AsyncStateMachineAttributeQualifiedName
					) ?? true;

			return new BaseObjectProperties
			{
				IsFromSource = false,
				Object = null,
				HasCoreMethod = coreMethod is not null,
				RequiresServiceProvider = validateAsyncWithServiceProvider is not null,
				IsAsync = isAsync,
			};
		}

		return null;
	}

	private static bool IsValidatable(INamedTypeSymbol typeSymbol)
	{
		return typeSymbol
			.GetAttributes()
			.Any(static attr => attr.AttributeClass?.GetQualifiedName() == Consts.ValidatableAttributeQualifiedName);
	}

	/// <summary>
	/// Find the nearest method of the given name, declared by the type or its ancestors
	/// </summary>
	private static IMethodSymbol? FindMethod(
		INamedTypeSymbol typeSymbol,
		string name,
		Func<IMethodSymbol, bool> predicate
	)
	{
		for (INamedTypeSymbol? type = typeSymbol; type is not null; type = type.BaseType)
		{
			foreach (var member in type.GetMembers(name))
			{
				if (member is IMethodSymbol { MethodKind: MethodKind.Ordinary } method && predicate(method))
				{
					return method;
				}
			}
		}

		return null;
	}

	private static PropertyProperties[] GetProperties(
		ImmutableArray<ISymbol> membersSymbols,
		SemanticModel semanticModel
	)
	{
		var list = new List<PropertyProperties>();

		foreach (var symbol in membersSymbols)
		{
			if (symbol is not IPropertySymbol propertySymbol)
			{
				continue;
			}

			list.Add(SymbolMapper.MapValidatableProperty(propertySymbol, semanticModel));
		}

		return list.ToArray();
	}

	private static MethodProperties[] GetMethods(ImmutableArray<ISymbol> membersSymbols, SemanticModel semanticModel)
	{
		var list = new List<MethodProperties>();

		foreach (var symbol in membersSymbols)
		{
			if (symbol is not IMethodSymbol methodSymbol)
			{
				continue;
			}

			if (
				methodSymbol.MethodKind
				is MethodKind.Ordinary
					or MethodKind.ExplicitInterfaceImplementation
					or MethodKind.DeclareMethod
			)
			{
				list.Add(SymbolMapper.MapMethod(methodSymbol, semanticModel));
			}
		}

		return list.ToArray();
	}

	private static bool? GetUseAutoValidatorsValue(AttributeData validatableAttribute)
	{
		if (
			validatableAttribute
				.NamedArguments.FirstOrDefault(static x =>
					x.Key == Consts.ValidatableAttributeUseAutoValidatorsPropertyName
				)
				.Value.Value
			is true
		)
		{
			return true;
		}

		if (
			validatableAttribute
				.NamedArguments.FirstOrDefault(static x =>
					x.Key == Consts.ValidatableAttributeNoAutoValidatorsPropertyName
				)
				.Value.Value
			is true
		)
		{
			return false;
		}

		return null;
	}

	private static bool? GetGetExitEarlyValue(AttributeData validatableAttribute)
	{
		if (
			validatableAttribute
				.NamedArguments.FirstOrDefault(static x => x.Key == Consts.ValidatableAttributeUseExitEarlyPropertyName)
				.Value.Value
			is true
		)
		{
			return true;
		}

		if (
			validatableAttribute
				.NamedArguments.FirstOrDefault(static x => x.Key == Consts.ValidatableAttributeNoAExitEarlyPropertyName)
				.Value.Value
			is true
		)
		{
			return false;
		}

		return null;
	}

	private static UsingDirectiveSyntax[] GetUsings(TypeDeclarationSyntax targetNode)
	{
		int max = 5;
		var target = targetNode.Parent;

		while (max >= 0 && target is not null && target is not CompilationUnitSyntax)
		{
			target = target.Parent;
			max--;
		}

		// Global usings apply to the whole compilation already; copying them would produce invalid code
		var usings = target is CompilationUnitSyntax cus
			? cus.Usings.Where(static usingSyntax => usingSyntax.GlobalKeyword.IsKind(SyntaxKind.None)).ToArray()
			: Array.Empty<UsingDirectiveSyntax>();
		return usings;
	}
}
